-- 4. Create word_relations table (for cross-dialect synonyms, variants, antonyms, derived words)
CREATE TABLE IF NOT EXISTS public.word_relations (
  id                 bigint                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_headword_id bigint                   NOT NULL REFERENCES public.headwords(id) ON DELETE CASCADE,
  target_headword_id bigint                   NOT NULL REFERENCES public.headwords(id) ON DELETE CASCADE,
  relation_type      text                     NOT NULL DEFAULT 'synonym' CHECK (relation_type IN ('synonym', 'variant', 'antonym', 'derived')),
  user_id            uuid                     REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at         timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT word_relations_no_self_link CHECK (source_headword_id <> target_headword_id),
  CONSTRAINT word_relations_unique UNIQUE (source_headword_id, target_headword_id, relation_type)
);

CREATE INDEX IF NOT EXISTS word_relations_source_idx ON public.word_relations(source_headword_id);
CREATE INDEX IF NOT EXISTS word_relations_target_idx ON public.word_relations(target_headword_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.word_relations TO anon, authenticated, service_role;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.word_relations_id_seq TO anon, authenticated, service_role;

-- 5. Make handle_vote_update() SECURITY DEFINER so voting works with RLS enabled
CREATE OR REPLACE FUNCTION public.handle_vote_update()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
BEGIN
  IF (TG_OP = 'INSERT') THEN
    IF NEW.definition_id IS NOT NULL THEN
      UPDATE definitions SET vote_score = COALESCE(vote_score, 0) + NEW.value WHERE id = NEW.definition_id;
    ELSIF NEW.example_id IS NOT NULL THEN
      UPDATE examples SET vote_score = COALESCE(vote_score, 0) + NEW.value WHERE id = NEW.example_id;
    END IF;
    RETURN NEW;

  ELSIF (TG_OP = 'DELETE') THEN
    IF OLD.definition_id IS NOT NULL THEN
      UPDATE definitions SET vote_score = COALESCE(vote_score, 0) - OLD.value WHERE id = OLD.definition_id;
    ELSIF OLD.example_id IS NOT NULL THEN
      UPDATE examples SET vote_score = COALESCE(vote_score, 0) - OLD.value WHERE id = OLD.example_id;
    END IF;
    RETURN OLD;

  ELSIF (TG_OP = 'UPDATE') THEN
    IF NEW.definition_id IS NOT NULL THEN
      UPDATE definitions SET vote_score = COALESCE(vote_score, 0) - OLD.value + NEW.value WHERE id = NEW.definition_id;
    ELSIF NEW.example_id IS NOT NULL THEN
      UPDATE examples SET vote_score = COALESCE(vote_score, 0) - OLD.value + NEW.value WHERE id = NEW.example_id;
    END IF;
    RETURN NEW;
  END IF;

  RETURN NULL;
END;
$function$;

-- 6. Helper function to normalize Amazigh Latin text to plain ASCII for tolerant search
CREATE OR REPLACE FUNCTION public.normalize_amazigh_latin(input_text text)
  RETURNS text
  LANGUAGE sql
  IMMUTABLE
  AS $$
    SELECT translate(
      replace(
        replace(
          replace(lower(COALESCE(input_text, '')), 'gh', 'ɣ'),
          '3', 'ɛ'
        ),
        'ch', 'c'
      ),
      'γγεḍṭẓḥṣṛčǧăâîûêô',
      'ɣɣɛdtzhsrcgaaiueo'
    );
  $$;

GRANT EXECUTE ON FUNCTION public.normalize_amazigh_latin(text) TO PUBLIC, anon, authenticated, service_role;

-- 7. Upgrade search_dictionary RPC to support:
--    - Exact/Prefix/Trigram & ASCII-normalized Latin headwords
--    - Tifinagh & Arabic script search
--    - Inflected form search (construct_state / plural inside definitions.attributes)
--    - Reverse definition search (English/French/Arabic meaning -> Amazigh headword)
DROP FUNCTION IF EXISTS public.search_dictionary(text);

CREATE OR REPLACE FUNCTION public.search_dictionary(term text)
  RETURNS TABLE (
    id              bigint,
    slug            text,
    headword_text   text,
    script_tifinagh text,
    script_arabic   text,
    match_type      text,
    match_preview   text,
    similarity      real
  )
  LANGUAGE plpgsql
  STABLE
  AS $function$
DECLARE
  clean_term text := trim(COALESCE(term, ''));
  norm_term  text := public.normalize_amazigh_latin(clean_term);
BEGIN
  IF char_length(clean_term) < 1 THEN
    RETURN;
  END IF;

  RETURN QUERY
  WITH raw_matches AS (
    -- A. Direct Headword Matches (Latin, Normalized ASCII, Tifinagh, Arabic)
    SELECT
      h.id,
      h.slug,
      h.script_latin AS headword_text,
      h.script_tifinagh,
      h.script_arabic,
      'headword'::text AS match_type,
      COALESCE(
        (SELECT d.definition_text FROM public.definitions d WHERE d.headword_id = h.id ORDER BY d.vote_score DESC NULLS LAST LIMIT 1),
        ''
      ) AS match_preview,
      GREATEST(
        CASE
          WHEN lower(h.script_latin) = lower(clean_term) THEN 1.0
          WHEN public.normalize_amazigh_latin(h.script_latin) = norm_term THEN 0.98
          WHEN h.script_tifinagh = clean_term OR h.script_arabic = clean_term THEN 1.0
          WHEN lower(h.script_latin) LIKE lower(clean_term) || '%' THEN 0.90
          WHEN public.normalize_amazigh_latin(h.script_latin) LIKE norm_term || '%' THEN 0.88
          WHEN h.script_tifinagh LIKE '%' || clean_term || '%' THEN 0.85
          WHEN h.script_arabic LIKE '%' || clean_term || '%' THEN 0.85
          ELSE 0.0
        END,
        similarity( COALESCE(h.script_latin, ''), clean_term ),
        similarity( public.normalize_amazigh_latin(h.script_latin), norm_term )
      )::real AS sim_score
    FROM public.headwords h
    WHERE
      h.script_latin ILIKE '%' || clean_term || '%'
      OR public.normalize_amazigh_latin(h.script_latin) LIKE '%' || norm_term || '%'
      OR h.script_latin % clean_term
      OR h.script_tifinagh ILIKE '%' || clean_term || '%'
      OR h.script_arabic ILIKE '%' || clean_term || '%'

    UNION ALL

    -- B. Inflected Form Matches (Construct State / Addad Amaruz or Plural in definitions.attributes)
    SELECT
      h.id,
      h.slug,
      h.script_latin AS headword_text,
      h.script_tifinagh,
      h.script_arabic,
      'inflected'::text AS match_type,
      CASE
        WHEN public.normalize_amazigh_latin(d.attributes->>'construct_state') LIKE '%' || norm_term || '%'
          THEN 'Construct state: ' || (d.attributes->>'construct_state')
        ELSE 'Plural: ' || (d.attributes->>'plural')
      END AS match_preview,
      0.82::real AS sim_score
    FROM public.definitions d
    JOIN public.headwords h ON h.id = d.headword_id
    WHERE
      (
        (d.attributes ? 'construct_state' AND public.normalize_amazigh_latin(d.attributes->>'construct_state') LIKE '%' || norm_term || '%')
        OR
        (d.attributes ? 'plural' AND public.normalize_amazigh_latin(d.attributes->>'plural') LIKE '%' || norm_term || '%')
      )

    UNION ALL

    -- C. Reverse Definition / Meaning Matches
    SELECT
      h.id,
      h.slug,
      h.script_latin AS headword_text,
      h.script_tifinagh,
      h.script_arabic,
      'meaning'::text AS match_type,
      d.definition_text AS match_preview,
      CASE
        WHEN d.definition_text ILIKE clean_term || '%' THEN 0.78
        ELSE 0.65
      END::real AS sim_score
    FROM public.definitions d
    JOIN public.headwords h ON h.id = d.headword_id
    WHERE
      d.definition_text ILIKE '%' || clean_term || '%'
  ),
  deduped AS (
    SELECT DISTINCT ON (rm.id)
      rm.id,
      rm.slug,
      rm.headword_text,
      rm.script_tifinagh,
      rm.script_arabic,
      rm.match_type,
      rm.match_preview,
      rm.sim_score AS similarity
    FROM raw_matches rm
    ORDER BY rm.id, rm.sim_score DESC
  )
  SELECT
    dd.id,
    dd.slug,
    dd.headword_text,
    dd.script_tifinagh,
    dd.script_arabic,
    dd.match_type,
    dd.match_preview,
    dd.similarity
  FROM deduped dd
  ORDER BY dd.similarity DESC, dd.headword_text ASC
  LIMIT 10;
END;
$function$;

