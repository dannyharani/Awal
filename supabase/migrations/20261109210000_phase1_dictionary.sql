-- 8. Security helper functions & Triggers
CREATE OR REPLACE FUNCTION public.is_moderator_or_admin()
  RETURNS boolean
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path = public
  STABLE
  AS $$
    SELECT EXISTS (
      SELECT 1 FROM public.profiles
      WHERE id = auth.uid()
        AND role IN ('moderator', 'instructor', 'admin')
    );
  $$;

GRANT EXECUTE ON FUNCTION public.is_moderator_or_admin() TO PUBLIC, anon, authenticated, service_role;

-- Prevent non-admins from escalating their own role or reputation_points
CREATE OR REPLACE FUNCTION public.protect_profile_privileged_fields()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = public
  AS $$
BEGIN
  IF current_setting('role', true) = 'authenticated' THEN
    IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin') THEN
      NEW.role := OLD.role;
      NEW.reputation_points := OLD.reputation_points;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trigger_protect_profile_fields ON public.profiles;
CREATE TRIGGER trigger_protect_profile_fields
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.protect_profile_privileged_fields();

